// خلط مصفوفة (نسخة جديدة)
function shuffleArray(arr) {
    const copy = arr.slice();
    for (let i = copy.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
}

function startQuiz(mode = 'full') {
    lastQuizMode = mode;
    const pool = shuffleArray(quizQuestions);
    activeQuizQuestions = mode === 'quick' ? pool.slice(0, 20) : pool;

    document.getElementById('quizStart').style.display = 'none';
    document.getElementById('quizContainer').style.display = 'block';
    document.getElementById('quizResult').style.display = 'none';
    document.getElementById('quizProgressBar').style.width = '0%';
    currentQuizQuestion = 0;
    quizScore = 0;
    loadQuizQuestion();
}

function loadQuizQuestion() {
    const q = activeQuizQuestions[currentQuizQuestion];
    selectedAnswer = -1;
    quizAnswered = false;
    
    document.getElementById('questionCounter').textContent = `السؤال ${currentQuizQuestion + 1} / ${activeQuizQuestions.length}`;
    document.getElementById('questionTopic').textContent = `الموضوع: ${q.topic}`;
    document.getElementById('quizQuestionText').textContent = q.question;

    const progress = ((currentQuizQuestion) / activeQuizQuestions.length) * 100;
    document.getElementById('quizProgressBar').style.width = progress + '%';
    
    const optionsDiv = document.getElementById('quizOptions');
    optionsDiv.innerHTML = '';

    // خلط الخيارات حتى لا يكون الجواب دائماً في نفس الموقع
    optionOrder = q.options.map((_, i) => i);
    for (let i = optionOrder.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [optionOrder[i], optionOrder[j]] = [optionOrder[j], optionOrder[i]];
    }
    currentCorrectPosition = optionOrder.indexOf(q.correctAnswerIndex);
    
    const letters = ['أ', 'ب', 'ج', 'د'];
    optionOrder.forEach((originalIndex, position) => {
        const optionDiv = document.createElement('div');
        optionDiv.className = 'quiz-option';
        optionDiv.innerHTML = `
            <div class="option-letter">${letters[position]}</div>
            <div class="option-text">${q.options[originalIndex]}</div>
        `;
        optionDiv.onclick = () => selectOption(position, optionDiv);
        optionsDiv.appendChild(optionDiv);
    });
    
    document.getElementById('quizExplanation').style.display = 'none';
    document.getElementById('checkAnswerBtn').style.display = 'block';
    document.getElementById('nextQuestionBtn').style.display = 'none';
    document.getElementById('checkAnswerBtn').disabled = true;
}

function selectOption(index, element) {
    if (quizAnswered) return;
    
    document.querySelectorAll('.quiz-option').forEach(opt => {
        opt.classList.remove('selected');
    });
    
    element.classList.add('selected');
    selectedAnswer = index;
    document.getElementById('checkAnswerBtn').disabled = false;
}

function checkAnswer() {
    if (selectedAnswer === -1 || quizAnswered) return;
    
    quizAnswered = true;
    const q = activeQuizQuestions[currentQuizQuestion];
    const options = document.querySelectorAll('.quiz-option');
    
    options.forEach((opt, index) => {
        opt.classList.add('disabled');
        opt.onclick = null;
        
        if (index === currentCorrectPosition) {
            opt.classList.add('correct');
        } else if (index === selectedAnswer) {
            opt.classList.add('wrong');
        }
    });
    
    if (selectedAnswer === currentCorrectPosition) {
        quizScore++;
    }
    
    document.getElementById('quizExplanationText').textContent = q.explanation;
    document.getElementById('quizExplanation').style.display = 'block';
    
    document.getElementById('checkAnswerBtn').style.display = 'none';
    document.getElementById('nextQuestionBtn').style.display = 'block';
}

function nextQuestion() {
    currentQuizQuestion++;
    if (currentQuizQuestion < activeQuizQuestions.length) {
        loadQuizQuestion();
        document.getElementById('quizContainer').scrollIntoView({ behavior: 'smooth', block: 'start' });
    } else {
        showQuizResult();
    }
}

function showQuizResult() {
    document.getElementById('quizContainer').style.display = 'none';
    document.getElementById('quizResult').style.display = 'block';
    document.getElementById('quizProgressBar').style.width = '100%';
    
    document.getElementById('finalScore').textContent = quizScore;
    document.getElementById('totalQuestions').textContent = activeQuizQuestions.length;
    
    const percentage = (quizScore / activeQuizQuestions.length) * 100;
    let message = '';
    if (percentage >= 90) message = 'ممتاز جداً! أحسنت 🎉';
    else if (percentage >= 80) message = 'جيد جداً 👍';
    else if (percentage >= 70) message = 'جيد 👌';
    else if (percentage >= 60) message = 'مقبول';
    else message = 'تحتاج للمراجعة 📚';
    
    document.getElementById('resultMessage').textContent = message;
    document.getElementById('quizResult').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function restartQuiz() {
    resetQuiz();
    startQuiz(lastQuizMode);
}

