function renderClassmates() {
    const grid = document.getElementById('eggGrid');
    grid.innerHTML = '';
    classmates.forEach((person, index) => {
        const card = document.createElement('div');
        card.className = 'egg-card';
        card.style.animationDelay = (index * 0.07) + 's';
        card.innerHTML = `
            <div class="egg-avatar" style="border-color:${person.color}; color:${person.color};">${person.emoji}</div>
            <h3 class="egg-name">${person.name}</h3>
            <span class="egg-tag" style="color:${person.color}; border-color:${person.color}40; background:${person.color}14;">${person.title}</span>
            <p class="egg-desc">${person.desc}</p>
            <span class="egg-open" style="color:${person.color};">اضغط لسرّك ↙</span>
        `;
        card.setAttribute('role', 'button');
        card.setAttribute('tabindex', '0');
        card.setAttribute('aria-label', 'فتح سر ' + person.name);
        card.addEventListener('click', () => openPersonEgg(index));
        card.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' || e.key === ' ') {
                e.preventDefault();
                openPersonEgg(index);
            }
        });
        grid.appendChild(card);
    });
}

